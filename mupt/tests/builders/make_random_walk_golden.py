"""
Record golden placements from the PRE-PATCH AngleConstrainedRandomWalk
(run on unmodified mupt/builders/random_walk.py at commit 1aeddd2 + Patch 1)

Run with PYTHONHASHSEED=0: the pre-patch walker picks each chain's walk direction
in hash-dependent set order, and seed 0 gives the topology-insertion order
(head = first-inserted terminus) that the patched walker uses deterministically

Writes mupt/tests/builders/random_walk_golden.py
"""

from pathlib import Path

import numpy as np

from mupt.builders.random_walk import AngleConstrainedRandomWalk
from mupt.tests.builders.walk_helpers import (
    GOLDEN_CHAIN_SEED,
    GOLDEN_GLOBAL_SEED,
    GOLDEN_SCENARIOS,
    synthetic_chains,
)

OUT = Path(__file__).parent / "random_walk_golden.py"


def record() -> dict[str, list[tuple[tuple, list[list[float]]]]]:
    """Placements (as 4x4 matrices) produced by the walker for each golden scenario"""
    golden = {}
    for name, (walk_kwargs, rng_seed, chain_lengths) in GOLDEN_SCENARIOS.items():
        primitive, _ = synthetic_chains(chain_lengths, seed=GOLDEN_CHAIN_SEED)
        np.random.seed(GOLDEN_GLOBAL_SEED)
        rng = None if (rng_seed is None) else np.random.default_rng(rng_seed)
        builder = AngleConstrainedRandomWalk(**walk_kwargs, rng=rng)
        golden[name] = [
            (handle, transform.as_matrix().tolist())
            for handle, transform in builder.generate_placements(primitive)
        ]
    return golden


if __name__ == "__main__":
    golden = record()
    lines = [
        "# ruff: noqa: E501",
        '"""Golden placements recorded from the pre-patch AngleConstrainedRandomWalk',
        "",
        "Generated by mupt/tests/builders/make_random_walk_golden.py",
        "(do not edit by hand)",
        '"""',
        "",
        "# fmt: off",
        "GOLDEN_PLACEMENTS = {",
    ]
    for name, placements in golden.items():
        lines.append(f"    {name!r}: [")
        for handle, matrix in placements:
            lines.append(f"        ({handle!r}, {matrix!r}),")
        lines.append("    ],")
    lines += ["}", "# fmt: on", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {sum(map(len, golden.values()))} placements to {OUT}")
